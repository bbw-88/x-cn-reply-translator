import { mkdir, cp, readFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { build } = require('esbuild');
const root = fileURLToPath(new URL('../', import.meta.url));
const dist = join(root, 'dist');
await mkdir(dist, {recursive:true});
const oldFiles = (await readdir(dist)).filter(x => ['models','vendor','background.js','engine.js'].includes(x));
if (oldFiles.length) throw new Error('Use a clean dist directory: '+oldFiles.join(', '));
await build({entryPoints:[join(root,'src/native-bridge.ts')],outfile:join(dist,'native-bridge.js'),bundle:true,format:'iife',target:'chrome138',legalComments:'eof'});
for (const file of ['manifest.json','reply.js']) await cp(join(root,'src',file),join(dist,file));
for (const file of ['LICENSE','README.md','THIRD_PARTY_NOTICES.md','UPSTREAM.md']) await cp(join(root,file),join(dist,file));
await mkdir(join(dist,'licenses'),{recursive:true});
await cp(join(root,'licenses/Native-Translate-LICENSE.txt'),join(dist,'licenses/Native-Translate-LICENSE.txt'));
const manifest = JSON.parse(await readFile(join(dist,'manifest.json'),'utf8'));
console.log('Built v'+manifest.version+' with Chrome on-device translation; no bundled model or background worker.');
